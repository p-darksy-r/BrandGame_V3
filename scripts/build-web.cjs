const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const postcss = require('postcss');
const tailwind = require('tailwindcss');
const { auditCatalog, categories } = require('./lib/catalog.cjs');
const root = path.resolve(__dirname, '..');
process.chdir(root);
const check = process.argv.includes('--check');
const outputs = new Map();
const put = (name, value) => outputs.set(name, name.endsWith('.woff2') ? value : Buffer.from(value.toString().replace(/\r\n/g, '\n')));
const copy = (from, to) => put(to, fs.readFileSync(from));

async function main() {
    const { catalog, excluded, corrected, selectedIcons } = auditCatalog(root);
    put('src/web/js/data/offline-catalog.js', '// Generated by npm run build:web; edit the category sources and scripts/lib/catalog.cjs.\nconst OFFLINE_CATALOG = ' + JSON.stringify(catalog, null, 2) + ';\n');
    const version = fs.readFileSync('VERSION', 'utf8').trim();
    if (JSON.parse(fs.readFileSync('package.json')).version !== version) throw new Error('package.json and VERSION differ.');
    put('src/web/js/core/version.js', `// Generated from VERSION.\nconst GAME_VERSION = ${JSON.stringify(version)};\n`);
    for (const [slug] of selectedIcons) copy(`node_modules/simple-icons/icons/${slug}.svg`, `src/web/assets/logos/${slug}.svg`);
    const fonts = { orbitron: [400, 700, 900], rajdhani: [500, 700] };
    let fontCss = '/* Locally bundled SIL Open Font License fonts. */\n';
    for (const [family, weights] of Object.entries(fonts)) {
        for (const weight of weights) {
            const name = `${family}-latin-${weight}-normal.woff2`;
            copy(`node_modules/@fontsource/${family}/files/${name}`, `src/web/assets/fonts/${name}`);
            fontCss += `@font-face{font-family:'${family === 'orbitron' ? 'Orbitron' : 'Rajdhani'}';font-style:normal;font-weight:${weight};font-display:swap;src:url('../assets/fonts/${name}') format('woff2')}\n`;
        }
        copy(`node_modules/@fontsource/${family}/LICENSE`, `src/web/licenses/${family}-OFL.txt`);
    }
    put('src/web/styles/fonts.css', fontCss);
    copy('node_modules/simple-icons/LICENSE.md', 'src/web/licenses/simple-icons-CC0.txt');
    copy('node_modules/tailwindcss/LICENSE', 'src/web/licenses/tailwindcss-MIT.txt');
    put('src/web/licenses/logo-sources.json', JSON.stringify([...selectedIcons.values()].map(({ title, slug, source, license, guidelines }) => ({ title, slug, source, license, guidelines })), null, 2) + '\n');
    put('src/web/licenses/README.txt', 'Logos: Simple Icons 9.21.0 (CC0). Individual brand guidelines and any additional licence information are in logo-sources.json. Brand names and trademarks belong to their respective owners; no affiliation is implied.\nFonts: Orbitron and Rajdhani via Fontsource 5.3.0 (SIL OFL).\nCSS utilities: Tailwind CSS 3.4.19 (MIT).\n');
    const css = await postcss([tailwind(require('../tailwind.config.cjs'))]).process('@tailwind base;\n@tailwind components;\n@tailwind utilities;\n', { from: undefined });
    put('src/web/styles/tailwind.css', css.css);
    let report = '# Auditoria do catálogo offline\n\nGerado por `npm run build:web`. Pacote fixado: Simple Icons 9.21.0. As fontes originais permanecem em `src/web/js/data`; apenas as identidades verificadas entram nas rondas. Nomes ambíguos e ícones de empresas-mãe não substituem logótipos em falta.\n\n';
    report += '| Categoria | Marcas disponíveis |\n|---|---:|\n' + categories.map(category => `| ${category} | ${catalog[category].length} |`).join('\n');
    report += `\n\nTotal: ${Object.values(catalog).flat().length} entradas, ${selectedIcons.size} ficheiros SVG únicos. Mantêm-se os 100 níveis por categoria, com reutilização de marcas. A validação cobre correspondência e disponibilidade dos ficheiros; não constitui uma nova autorização das marcas.\n\n## Correções de identificadores e pistas\n\n`;
    report += corrected.map(item => `- ${item.category}: ${item.name} — \`${item.oldSlug}\` → \`${item.slug}\`; ${item.hint}`).join('\n');
    report += `\n\n## Entradas fora das rondas (${excluded.length})\n\nPreservadas nas fontes para revisão futura; não são apagadas dos saves personalizados.\n\n`;
    report += excluded.map(item => `- ${item.category}: **${item.name}** (\`${item.oldSlug}\`) — ${item.reason}`).join('\n') + '\n';
    put('docs/CATALOG_AUDIT.md', report);
    const hashes = Object.fromEntries([...outputs].filter(([name]) => name.startsWith('src/web/')).map(([name, data]) => [name.substring(8), crypto.createHash('sha256').update(data).digest('hex')]));
    put('src/web/assets/manifest.json', JSON.stringify({ version, sources: { simpleIcons: '9.21.0', fontsource: '5.3.0', tailwind: '3.4.19' }, sha256: hashes }, null, 2) + '\n');
    for (const [name, data] of outputs) {
        if (check) {
            if (!fs.existsSync(name) || !fs.readFileSync(name).equals(data)) throw new Error(`Generated file is stale: ${name}. Run npm run build:web.`);
        } else {
            fs.mkdirSync(path.dirname(name), { recursive: true });
            fs.writeFileSync(name, data);
        }
    }
    console.log(`${check ? 'Verified' : 'Built'} ${outputs.size} local files; ${Object.values(catalog).flat().length} catalog entries, ${excluded.length} quarantined. No runtime downloads.`);
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
