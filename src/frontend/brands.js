// --- RUNTIME DECOMPRESSION ENGINE ---
function decompressPools() {
    const database = {};
    for (const [category, items] of Object.entries(RAW_COMPACT_POOLS)) {
        database[category] = items.map(rawString => {
            const [name, slug, hint] = rawString.split("|");
            return { name, slug, hint };
        });
    }
    return database;
}

const DECOMPRESSED_BRAND_DATABASE = decompressPools();

// --- PROCEDURAL DETERMINISTIC GENERATOR ---
function getBrandsForLevel(category, level) {
    const basePool = DECOMPRESSED_BRAND_DATABASE[category];
    if (!basePool || basePool.length === 0) return [];

    // Progressive scale: Level 1-10: 4 brands, Level 11-20: 5 brands ... up to 13 brands max
    const brandCount = Math.floor((level - 1) / 10) + 4;

    // Linear Congruential Generator (LCG) using Mersenne Prime seed to avoid repeats
    let seed = hashString(category) + level * $$7919$$;
    const selected = [];
    const poolCopy = [...basePool];

    for (let i = 0; i < brandCount; i++) {
        seed = (seed * $$1664525$$ + $$1013904223$$) % $$4294967296$$;
        const targetIndex = seed % poolCopy.length;
        const extracted = poolCopy.splice(targetIndex, 1)[0] || basePool[i % basePool.length];
        selected.push(extracted);
        if (poolCopy.length === 0) {
            poolCopy.push(...basePool);
        }
    }
    return selected;
}

function hashString(str) {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
        hash = (hash << 5) - hash + str.charCodeAt(i);
        hash |= 0;
    }
    return Math.abs(hash);
}

