// --- PROCEDURAL 100-LEVEL GENERATOR ENGINE ---
// Generates reproducible lists of brands for any level (1-100) dynamically using deterministic seeds.
function getBrandsForLevel(category, level) {
    const basePool = BASE_BRAND_POOL[category];
    if (!basePool || basePool.length === 0) return [];

    // Calculate dynamic brand count: every 10 levels, increase brand size by +1
    // Lvl 1-10: 4 brands, Lvl 11-20: 5 brands ... Lvl 91-100: 13 brands
    const brandCount = Math.floor((level - 1) / 10) + 4;

    // Use a LCG (Linear Congruential Generator) seeded on Level + Category hash
    let seed = hashString(category) + level * 7919; // Multiply by prime
    
    const selected = [];
    const poolCopy = [...basePool];

    for (let i = 0; i < brandCount; i++) {
        // Deterministic pseudo-random selection
        seed = (seed * 1664525 + 1013904223) % 4294967296;
        const targetIndex = seed % poolCopy.length;
        
        // Extract and inject
        const extracted = poolCopy.splice(targetIndex, 1)[0] || basePool[i % basePool.length];
        selected.push(extracted);
        
        // Re-insert pool components to prevent early pool exhaustions
        if (poolCopy.length === 0) {
            poolCopy.push(...basePool);
        }
    }

    return selected;
}

function hashString(str) {
    let hash = 0;
    for (let i = 0; i < str.length; i++) {
        hash = (hash << 5) - hash + str.charCodeAt(i);
        hash |= 0; // Convert to 32bit integer
    }
    return Math.abs(hash);
}

